// RefDir is the directory, relative to the repository root, the generated
// files live in.
const RefDir = "docs/reference"

// generatedNote opens every generated file.
const generatedNote = "<!-- Code generated by internal/docgen. DO NOT EDIT. -->\n" +
	"<!-- Run `go generate ./...` to regenerate this file from the code. -->\n\n"

// renderers maps each generated file name to its renderer.
var renderers = map[string]func() ([]byte, error){
	"metrics.md":     renderMetrics,
	"tokens.md":      renderTokens,
	"hash-scopes.md": renderHashScopes,
	"health.md":      renderHealth,
	"drill-rules.md": renderDrillRules,
}

// Files renders every reference document, keyed by its path relative to the
// repository root.
func Files() (map[string][]byte, error) {
	out := make(map[string][]byte, len(renderers))
	for name, render := range renderers {
		b, err := render()
		if err != nil {
			return nil, fmt.Errorf("docgen: %s: %w", name, err)
		}
		out[RefDir+"/"+name] = b
	}
	return out, nil
}

// Write renders every reference document under root.
func Write(root string) error {
	files, err := Files()
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(root, filepath.FromSlash(RefDir)), 0o755); err != nil {
		return err
	}
	for _, rel := range sortedKeys(files) {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.WriteFile(path, files[rel], 0o644); err != nil {
			return err
		}
	}
	return nil
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// doc is a small Markdown builder.
type doc struct{ bytes.Buffer }

func newDoc(title string) *doc {
	d := &doc{}
	d.WriteString(generatedNote)
	d.WriteString("# " + title + "\n\n")
	return d
}

func (d *doc) p(lines ...string) {
	d.WriteString(strings.Join(lines, "\n") + "\n\n")
}

func (d *doc) h2(s string) { d.WriteString("## " + s + "\n\n") }

func (d *doc) table(header []string, rows [][]string) {
	d.WriteString("| " + strings.Join(header, " | ") + " |\n")
	seps := make([]string, len(header))
	for i := range seps {
		seps[i] = "---"
	}
	d.WriteString("|" + strings.Join(seps, "|") + "|\n")
	for _, r := range rows {
		cells := make([]string, len(r))
		for i, c := range r {
			cells[i] = cell(c)
		}
		d.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}
	d.WriteString("\n")
}

func (d *doc) fence(lang, body string) {
	d.WriteString("```" + lang + "\n" + strings.TrimRight(body, "\n") + "\n```\n\n")
}

func (d *doc) bytes() []byte {
	return append(bytes.TrimRight(d.Bytes(), "\n"), '\n')
}

// cell escapes a value for a Markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}

func code(s string) string { return "`" + s + "`" }

func codeList(items []string) string {
	if len(items) == 0 {
		return "—"
	}
	out := make([]string, len(items))
	for i, s := range items {
		out[i] = code(s)
	}
	return strings.Join(out, ", ")
}

