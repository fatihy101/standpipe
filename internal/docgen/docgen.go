// Package docgen renders the reference documents under docs/reference from
// the code that owns each closed list. The code is the source of truth; the
// Markdown is an artefact of it.
//
// Run `go generate ./...` after changing any of the lists below. The test in
// this package fails when a committed file differs from what the generator
// would write now.
//
//	docs/reference/metrics.md      metrics.Catalog()
//	docs/reference/tokens.md       httpapi token patterns
//	docs/reference/hash-scopes.md  store.HashScopes(), store.RedactableFields()
//	docs/reference/health.md       httpapi.HealthFields(), httpapi.HealthExampleJSON()
//	docs/reference/drill-rules.md  shadow.DrillRules(), shadow.LedgerTables()
package docgen

