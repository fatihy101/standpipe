func renderMetrics() ([]byte, error) {
	d := newDoc("Metrics reference")
	d.p("The admin listener serves Prometheus metrics on `/metrics`. This table is the gateway's",
		"complete metric catalog (`metrics.Catalog()`), in catalog order. Recording a name that is",
		"not in the catalog, under a different type, or with a different label set is reported as",
		"`metrics_drift` on the admin `/healthz` (see [health.md](health.md)).")
	d.p("A row marked **declared, not emitted** is part of the contract but no code path records",
		"it yet: it does not appear on `/metrics`, and recording it is itself a drift entry.")
	d.p("Label values are bounded: every metric is capped at a fixed number of series, and no",
		"metric carries a caller IP except `gateway_watched_ip_rejected_total`, whose `ip` label",
		"is the configured `observability.watch_ips` entry rather than the observed address.")

	var rows [][]string
	for _, m := range metrics.Catalog() {
		status := "emitted"
		if m.NotEmitted {
			status = "**declared, not emitted**"
		}
		rows = append(rows, []string{code(m.Name), string(m.Kind), codeList(m.Labels), status, m.Help})
	}
	d.table([]string{"Metric", "Type", "Labels", "Status", "Description"}, rows)

	d.h2("Histogram buckets")
	var hrows [][]string
	for _, m := range metrics.Catalog() {
		if m.Kind != metrics.KindHistogram {
			continue
		}
		buckets := m.Buckets
		if len(buckets) == 0 {
			buckets = metrics.DefaultBuckets
		}
		parts := make([]string, len(buckets))
		for i, b := range buckets {
			parts[i] = strconv.FormatFloat(b, 'g', -1, 64)
		}
		hrows = append(hrows, []string{code(m.Name), strings.Join(parts, ", ")})
	}
	d.table([]string{"Metric", "Upper bounds (seconds)"}, hrows)
	return d.bytes(), nil
}

func renderTokens() ([]byte, error) {
	d := newDoc("Caller token format")
	prefix := httpapi.TokenPrefix()
	d.p("A caller authenticates with a bearer token minted by `standpipe token create`. The",
		"plaintext is printed exactly once and stored nowhere; the configuration holds only its",
		"SHA-256 hash (`token_hash: \"sha256:…\"`).")
	d.h2("Format")
	d.fence("text", prefix+"_<token_id>_<secret>_<checksum>")
	d.table([]string{"Field", "Pattern", "Notes"}, [][]string{
		{"prefix", code(prefix), "Fixed. It marks the token type."},
		{"`token_id`", code(httpapi.TokenIDPattern()), "The id named in the caller's `token_id`. It may itself contain `_` and `-`, so a token is parsed right to left."},
		{"secret", code(httpapi.TokenSecretPattern()), "32 random bytes in base62, left-padded to exactly 43 characters."},
		{"checksum", code(httpapi.TokenChecksumPattern()), "CRC-32 (IEEE) of everything before the last `_`, in lower-case base36, unpadded. A truncated copy-paste fails here rather than looking like a wrong secret."},
	})
	d.h2("Secret-scanning regex")
	d.p("Use this pattern to find leaked tokens in logs, repositories and chat exports:")
	d.fence("text", httpapi.TokenScanPattern())
	d.p("It is unanchored on purpose, so it finds a token in the middle of a line. A scanner",
		"should treat only a **full** match of a token-shaped string as a finding.")
	d.p("This is the exact pattern the minter enforces. Before `standpipe token create` prints a",
		"token it runs the token through the gateway's own parser and through this regex, and if",
		"either rejects it the command fails and prints nothing. A token this build mints is",
		"therefore always one this pattern matches in full.")
	d.h2("Authentication")
	d.p("Every authentication failure (malformed header, wrong format, bad checksum, unknown",
		"token id, wrong secret) returns the same `401` with no detail.")
	return d.bytes(), nil
}

func renderHashScopes() ([]byte, error) {
	d := newDoc("Trigger-log hash scopes")
	d.p("Every row of the trigger log carries `content_sha256`, the SHA-256 of a canonical JSON",
		"object built from the row. `standpipe verify` recomputes it. The **hash scope** is the closed",
		"list of fields that object contains: a field outside the scope can change without",
		"`verify` noticing, so each list below is exhaustive. A field not named here is not",
		"covered by the hash.")
	d.p("Dotted names (`caller.token_id`) are members of a nested object in the canonical form.",
		"Every key is always present; an unset value is hashed as `null`, so the key set never",
		"depends on the row's values.")
	d.h2("Redactable fields")
	d.p("`standpipe forget` sets these fields to NULL on `trigger` and `trigger_rejected` rows",
		"older than a cut-off. They are outside every hash scope, so a redacted row still verifies:")
	d.p(codeList(store.RedactableFields()))
	for _, s := range store.HashScopes() {
		d.h2(code(s.EventType))
		d.p("**In scope:** " + codeList(s.Fields) + ".")
		if len(s.Excluded) > 0 {
			var rows [][]string
			for _, ex := range s.Excluded {
				rows = append(rows, []string{code(ex.Field), ex.Reason})
			}
			d.p("**Outside the scope:**")
			d.table([]string{"Field", "Why"}, rows)
		}
		if s.Note != "" {
			d.p(s.Note)
		}
	}
	return d.bytes(), nil
}

func renderHealth() ([]byte, error) {
	d := newDoc("Detailed health (`/healthz` on the admin listener)")
	d.p("The public listener's `/healthz` returns only `{\"status\": \"ok\"}` or",
		"`{\"status\": \"degraded\"}`. The admin listener's `/healthz` returns the detailed body",
		"below, with status `200`, or `503` when `sqlite_ok` is false.")
	d.h2("Fields")
	d.p("This list is **closed**: it is every key the body can carry. A key marked as possibly",
		"absent is not written at all in that case, and its absence has a meaning of its own.")
	var rows [][]string
	for _, f := range httpapi.HealthFields() {
		rows = append(rows, []string{code(f.Name), f.Meaning, f.Presence})
	}
	d.table([]string{"Field", "Meaning", "Present"}, rows)
	d.h2("Example")
	d.p("A healthy moment: GitHub has been called at least once since start-up, so",
		"`github_last_call_at` is present, and the metric catalog agrees with the code, so",
		"`metrics_drift` is absent.")
	example, err := httpapi.HealthExampleJSON()
	if err != nil {
		return nil, err
	}
	d.fence("json", string(example))
	d.h2("Reading `github_reachable`")
	d.p("The verdict has three states and a bool alone cannot carry them; the third is the",
		"absence of `github_last_call_at`.")
	d.table([]string{"Seen", "Meaning", "What to do"}, [][]string{
		{"`github_reachable: false`, `github_last_call_at` present", "GitHub is not answering: a transport failure.", "Follow the [runbook](../runbook.md)."},
		{"`github_reachable: false`, `github_last_call_at` absent", "No GitHub call has been classified since start-up. This is not a claim about GitHub.", "Wait, or trigger a call. Do not go to the runbook."},
		{"`github_reachable: true` but dispatches fail", "GitHub answers and rejects **our** identity.", "Check the App key, `app_id` and the installation, not GitHub's status page."},
	})
	d.p("`github_rate_observed` is the precondition for `github_rate_remaining` and",
		"`github_rate_reset_at`. GitHub omits rate-limit headers on authentication failures, so it",
		"can stay false while GitHub is reachable.")
	return d.bytes(), nil
}

func renderDrillRules() ([]byte, error) {
	d := newDoc("Drill candidate axis: rules and the schema objects that hold them")
	d.p("Phase 1's shadow ledger (`shadow.db`) records every run the drill selector looked at",
		"(`drill_candidate`), the time zone its day keys are drawn in (`drill_day_zone`), and the",
		"attempts planned for a selected run (`drill_attempt`). Each rule below names the CHECK",
		"constraint, trigger or index that holds it in the shipped migrations, so a constraint",
		"violation reaches the operator under the same name this table uses.")
	d.p("A test builds the schema from the shipped migrations and checks the names in both",
		"directions (every name here exists, and every named object on these tables is listed",
		"here), then writes rows each rule allows and forbids and requires SQLite to refuse the",
		"forbidden ones with an error attributed to the named object.")
	d.p("Rules without a name are held by a structural constraint SQLite does not name (a",
		"foreign key, a UNIQUE column), by the absence of a constraint, or by an order, which no",
		"CHECK can express.")
	d.h2("Rules")
	var rows [][]string
	for _, r := range shadow.DrillRules() {
		held := codeList(r.Objects)
		if r.Hold != shadow.HeldByName {
			held = "— *" + r.Hold.String() + "*: " + r.HeldBy
		}
		rows = append(rows, []string{strconv.Itoa(r.Num), code(r.Table), r.Rule, held})
	}
	d.table([]string{"#", "Table", "Rule", "Held by"}, rows)
	d.h2("Ledger tables")
	d.p("Every table the `shadow.db` migrations build. A test compares this list with the schema",
		"in both directions, so a new table cannot ship unlisted.")
	var trows [][]string
	for _, lt := range shadow.LedgerTables() {
		trows = append(trows, []string{code(lt.Name), lt.Axis, lt.Purpose})
	}
	d.table([]string{"Table", "Axis", "Purpose"}, trows)
	return d.bytes(), nil
}
